export function openingName(sans) {
  let best = null, bestLen = 0;
  for (const [name, seq] of OPENINGS) {
    if (seq.length > sans.length || seq.length < bestLen) continue;
    if (seq.every((m, i) => m === sans[i])) { best = name; bestLen = seq.length; }
  }
  return best;
}
